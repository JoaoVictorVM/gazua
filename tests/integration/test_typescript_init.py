import shutil
from pathlib import Path

from typescript_support import TypeScriptProject, require_typescript

from conftest import build_clean_environment
from gazua.config.loader import load_config


def init(project: TypeScriptProject, *arguments: str) -> object:
    env = {**build_clean_environment(), "PYTHONIOENCODING": "utf-8"}
    return project.cli("init", *arguments, env=env)


def test_init_describes_the_module_without_calling_it(tmp_path: Path) -> None:
    require_typescript()
    project = TypeScriptProject(tmp_path / "project")
    (project.root / "gazua.yaml").unlink()

    result = init(
        project,
        "--typescript",
        "dist/agent.js",
        "--typescript-export",
        "entrypoint",
        "--typescript-output-sink",
        "sink",
    )

    assert result.returncode == 0, result.stderr
    assert "imports dist/agent.js in Node" in result.stderr
    assert "delete_account: sensitive, dry-run until reviewed" in result.stdout
    text = (project.root / "gazua.yaml").read_text(encoding="utf-8")
    assert "Generated by gazua init --typescript" in text
    assert "    safe: true" not in text
    config = load_config(project.root / "gazua.yaml").config
    assert config.typescript is not None
    assert config.typescript.output_sink_export == "sink"
    assert sorted(config.tools) == [
        "delete_account",
        "get_order",
        "read_memory",
        "refund",
        "search_docs",
    ]
    assert all(not tool.safe for tool in config.tools.values())
    # Importing the module registered the tools; neither the entrypoint nor a tool ran.
    assert project.effects() == []
    assert ".gazua/" in (project.root / ".gitignore").read_text(encoding="utf-8")


def test_init_refuses_contradictions_and_missing_pieces_before_node(tmp_path: Path) -> None:
    require_typescript()
    project = TypeScriptProject(tmp_path / "project")
    (project.root / "gazua.yaml").unlink()

    mixed = init(
        project, "--typescript", "dist/agent.js", "--typescript-export", "x", "--entrypoint", "a:b"
    )
    assert mixed.returncode == 2
    assert "declares the target alone" in mixed.stderr
    no_export = init(project, "--typescript", "dist/agent.js")
    assert no_export.returncode == 2
    source = init(project, "--typescript", "src/agent.ts", "--typescript-export", "entrypoint")
    assert source.returncode == 2
    orphan = init(project, "--typescript-export", "entrypoint")
    assert orphan.returncode == 2
    assert not (project.root / "gazua.yaml").exists()

    shutil.rmtree(project.root / "node_modules")
    missing = init(project, "--typescript", "dist/agent.js", "--typescript-export", "entrypoint")
    assert missing.returncode == 2
    assert "typescript_package_missing" in missing.stderr
    assert "npm install --save-dev gazua" in missing.stderr
    assert not (project.root / "gazua.yaml").exists()

    agent = project.root / "dist" / "agent.js"
    agent.unlink()
    unbuilt = init(project, "--typescript", "dist/agent.js", "--typescript-export", "entrypoint")
    assert unbuilt.returncode == 2
    assert "build the project" in unbuilt.stderr


def test_tools_mode_refuses_a_typescript_target_without_node(tmp_path: Path) -> None:
    require_typescript()
    project = TypeScriptProject(tmp_path / "project")

    refused = project.cli(
        "run", "--tools", env={**build_clean_environment(), "PYTHONIOENCODING": "utf-8"}
    )

    assert refused.returncode == 2
    assert "use --agent for a TypeScript target" in refused.stderr
    assert project.effects() == []
