"""Prepares a project: discovers tools, suggests classes and writes reviewable files."""

from __future__ import annotations

import json
import os
import re
import shutil
import tempfile
from dataclasses import dataclass
from pathlib import Path

from gazua.config.diagnostics import ConfigError, Diagnostic, sanitize
from gazua.config.loader import load_config_text
from gazua.config.models import SCHEMA_URL
from gazua.config.references import is_reference
from gazua.discovery import DiscoveryResult, discover_tools

CONFIG_NAME = "gazua.yaml"
GITIGNORE_NAME = ".gitignore"
IGNORE_RULE = b".gazua/"

SENSITIVE_PREFIXES = ("delete_", "refund_", "send_", "update_", "write_", "execute_")

_PLAIN_KEY = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
_YAML_WORDS = frozenset({"null", "true", "false", "yes", "no", "on", "off", "y", "n"})
_IGNORING_RULES = frozenset({b".gazua", b".gazua/", b"/.gazua", b"/.gazua/", b"**/.gazua/"})


@dataclass(frozen=True, slots=True)
class InitResult:
    config_path: Path
    gitignore_path: Path
    gitignore_changed: bool
    discovery: DiscoveryResult
    warnings: tuple[Diagnostic, ...]
    entrypoint: str | None

    @property
    def ready_to_run(self) -> bool:
        return self.entrypoint is not None and bool(self.discovery.tools)


@dataclass(frozen=True, slots=True)
class _GitignorePlan:
    path: Path
    original: bytes | None
    updated: bytes | None
    reincluded: bool


def _io_error(file: Path | str | None, message: str) -> ConfigError:
    return ConfigError(
        [Diagnostic(code="config_io", file=str(file) if file else None, message=message)]
    )


def suggests_sensitive(name: str) -> bool:
    """A hint for the reviewer. A name proves neither what a tool does nor that it is safe."""
    return name.lower().startswith(SENSITIVE_PREFIXES)


def check_target(root: Path) -> None:
    """Fails before anything is read or written when the target cannot be initialized."""
    if not root.is_dir():
        raise _io_error(root, "The target directory does not exist.")
    config_path = root / CONFIG_NAME
    # lexists also sees a dangling symlink, which an exists check would report as free.
    if os.path.lexists(config_path):
        raise ConfigError(
            [
                Diagnostic(
                    code="config_exists",
                    file=str(config_path),
                    message="A configuration already exists and was kept; edit it manually.",
                )
            ]
        )


def _yaml_key(name: str) -> str:
    if _PLAIN_KEY.fullmatch(name) and name.lower() not in _YAML_WORDS:
        return name
    return json.dumps(name, ensure_ascii=False)


def render_config(discovery: DiscoveryResult, entrypoint: str | None) -> str:
    lines = [
        f"# yaml-language-server: $schema={SCHEMA_URL}",
        "#",
        "# Generated by gazua init. Treat this file as code: entrypoint and the target hooks",
        "# point to Python functions that a future execution can import and call.",
        "# Review every declaration below before relying on it.",
        "",
        "schema_version: 1",
        "",
    ]
    if entrypoint is None:
        lines += [
            "# REVIEW REQUIRED: set this to your test entrypoint, as module:attribute.",
            "entrypoint: null",
        ]
    else:
        lines += [
            "# REVIEW REQUIRED: confirm that this reference is your test entrypoint.",
            f"entrypoint: {json.dumps(entrypoint, ensure_ascii=False)}",
        ]
    lines.append("")
    if not discovery.complete:
        lines += [
            "# REVIEW REQUIRED: discovery was incomplete. Declare any missing tool manually.",
        ]
    if not discovery.tools:
        lines.append("tools: {}")
    else:
        lines.append("tools:")
    for tool in discovery.tools:
        if suggests_sensitive(tool.name):
            lines.append(
                "  # REVIEW REQUIRED: sensitive suggested from the name only. This is not "
                "proof of behavior or authorization."
            )
        else:
            lines.append(
                "  # REVIEW REQUIRED: not classified. Declare sensitive or forbidden. The tool "
                "stays in dry-run without them."
            )
        lines.append(f"  {_yaml_key(tool.name)}:")
        lines.append("    safe: false")
        if suggests_sensitive(tool.name):
            lines.append("    sensitive: true")
    return "\n".join(lines) + "\n"


def _line_ending(content: bytes) -> bytes:
    crlf = content.count(b"\r\n")
    return b"\r\n" if crlf and crlf >= content.count(b"\n") - crlf else b"\n"


def _plan_gitignore(root: Path) -> _GitignorePlan:
    path = root / GITIGNORE_NAME
    if path.is_symlink():
        raise _io_error(path, "This file is a symlink and was kept; add .gazua/ to it manually.")
    try:
        original = path.read_bytes()
    except FileNotFoundError:
        return _GitignorePlan(path, None, IGNORE_RULE + b"\n", reincluded=False)
    except OSError as error:
        raise _io_error(path, f"Could not read this file: {error.strerror}.") from None

    ignored = False
    reincluded = False
    for raw_line in original.removeprefix(b"\xef\xbb\xbf").splitlines():
        line = raw_line.rstrip(b" \t")
        if line.startswith(b"!") and b".gazua" in line:
            ignored, reincluded = False, True
        elif line in _IGNORING_RULES:
            ignored = True
    if ignored:
        return _GitignorePlan(path, original, None, reincluded=False)

    newline = _line_ending(original)
    separator = b"" if not original or original.endswith((b"\n", b"\r")) else newline
    updated = original + separator + IGNORE_RULE + newline
    return _GitignorePlan(path, original, updated, reincluded)


def _replace_gitignore(plan: _GitignorePlan) -> None:
    updated = plan.updated
    if updated is None:
        return
    if plan.original is None:
        with plan.path.open("xb") as stream:
            stream.write(updated)
        return
    descriptor, temporary_name = tempfile.mkstemp(dir=plan.path.parent, prefix=".gitignore.")
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(updated)
        shutil.copymode(plan.path, temporary)
        if plan.path.read_bytes() != plan.original:
            raise OSError("the file changed while Gazua was preparing the update")
        os.replace(temporary, plan.path)
    finally:
        temporary.unlink(missing_ok=True)


def _write_config(path: Path, content: str) -> None:
    # Exclusive creation also refuses a symlink, so a link can never redirect this write.
    try:
        with path.open("x", encoding="utf-8", newline="\n") as stream:
            stream.write(content)
    except FileExistsError:
        raise ConfigError(
            [
                Diagnostic(
                    code="config_exists",
                    file=str(path),
                    message="A configuration already exists and was kept; edit it manually.",
                )
            ]
        ) from None
    except OSError as error:
        raise _io_error(path, f"Could not write this file: {error.strerror}.") from None


def initialize_project(root: Path, entrypoint: str | None = None) -> InitResult:
    """Creates ``gazua.yaml`` and protects ``.gazua/``, without importing the project."""
    if entrypoint is not None and not is_reference(entrypoint):
        raise ConfigError(
            [
                Diagnostic(
                    code="invalid_field",
                    field="entrypoint",
                    message="Expected a reference in the form module:attribute.",
                )
            ]
        )
    check_target(root)
    config_path = root / CONFIG_NAME

    discovery = discover_tools(root)
    chosen_entrypoint = entrypoint if entrypoint is not None else discovery.entrypoint
    content = render_config(discovery, chosen_entrypoint)
    loaded = load_config_text(content, str(config_path))
    gitignore = _plan_gitignore(root)

    _write_config(config_path, content)
    try:
        _replace_gitignore(gitignore)
    except OSError as error:
        reason = sanitize(error.strerror or str(error))
        raise ConfigError(
            [
                Diagnostic(
                    code="config_io",
                    file=str(gitignore.path),
                    message=(
                        f"Created {CONFIG_NAME}, but could not update this file ({reason}). "
                        "Add .gazua/ to it yourself; the new configuration was kept."
                    ),
                )
            ]
        ) from None

    notes = list(discovery.warnings) + list(loaded.warnings)
    if gitignore.reincluded:
        notes.append(
            Diagnostic(
                code="gitignore_reinclude",
                severity="warning",
                file=str(gitignore.path),
                message="A rule re-included .gazua/, so an effective rule was added at the end.",
            )
        )
    return InitResult(
        config_path=config_path,
        gitignore_path=gitignore.path,
        gitignore_changed=gitignore.updated is not None,
        discovery=discovery,
        warnings=tuple(notes),
        entrypoint=chosen_entrypoint,
    )
